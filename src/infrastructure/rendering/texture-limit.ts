// Guard лимита высоты GPU-текстуры одной Skia-канвы (ревью ST-5, находка 5):
// канва вмещает весь документ (plan.heightPx, №28) — под неё выделяется
// GPU-поверхность, а максимальный размер поверхности ограничен железом
// (GL_MAX_TEXTURE_SIZE: типично 4096 px на бюджетных GPU, 8192 на большинстве
// современных, 16384 на флагманах). Канва выше лимита не отрисовывается:
// ожидаемо «пустая канва» при живой прокрутке (высота скролла считается по
// plan.heightPx) и работающем hit-тесте — самый незаметный вид отказа.
//
// Порог 8192 px — эвристика «большинства устройств», а не гарантия: на GPU
// с лимитом 4096 предупреждение сработает позже, чем канва реально опустеет.
// Настоящее решение — оконная отрисовка DrawWindow (№28): режим готов в
// plan.ts, подключается виртуализацией на этапе 6; guard лишь делает отказ
// заметным в журнале до того, как он всплывёт как «белый экран без причин».
//
// Слой Infrastructure (rendering): чистая функция без платформы и Skia —
// проверяется юнит-тестом. Решение «как предупреждать» — забота канвы
// (NotebookCanvas зовёт console.warn из useEffect, вне рендера): слой
// rendering не знает ни о React-цикле, ни о i18n представления.
//
// Единицы (2-й тур ревью ST-5, находка 2а): план и канва считают в логических
// px (dp), лимит GL_MAX_TEXTURE_SIZE — в физических; плотность дисплея
// (PixelRatio) применяется вызывающей стороной в месте вызова — функция
// остаётся чистой и сравнивает физические пиксели с физическим лимитом.

/**
 * Порог высоты канвы, выше которого GPU-поверхность может не создаться:
 * консервативная оценка «большинства современных устройств»
 * (GL_MAX_TEXTURE_SIZE ≥ 8192). Бюджетные GPU с лимитом 4096 покрываются
 * частично — см. шапку модуля.
 */
export const MAX_CANVAS_TEXTURE_HEIGHT_PX = 8192;

/**
 * Предупреждение о превышении лимита высоты GPU-текстуры или null, если
 * высота в пределах лимита (граница включительно: ровно 8192 — корректно).
 * Высота — в физических пикселях (логическая высота канвы × PixelRatio на
 * вызывающей стороне). Тотальна: NaN и отрицательные высоты дают null
 * (сравнение «>» ложно для NaN). Сообщение адресовано журналу разработчика
 * (console.warn), не UI.
 */
export function canvasTextureHeightWarning(canvasHeightPx: number): string | null {
  if (!(canvasHeightPx > MAX_CANVAS_TEXTURE_HEIGHT_PX)) {
    return null;
  }
  return (
    `NotebookCanvas: высота канвы ${canvasHeightPx} px превышает лимит ` +
    `GPU-текстуры ${MAX_CANVAS_TEXTURE_HEIGHT_PX} px — Skia может отрисовать ` +
    'пустую канву (прокрутка и hit-тест при этом работают). ' +
    'Виртуализация (DrawWindow, №28) — этап 6 дорожной карты.'
  );
}
