// Зашитая тема MVP (решение №32): единственный источник шрифтов, цветов и
// размеров рендера. Система тем с выбором шрифтов/цветов — после MVP (№32):
// в MVP потребители (Skia-рендер экрана, HTML→PDF, превью) импортируют этот
// объект напрямую и не хардкодят собственных шрифтов и цветов.
//
// Слой Infrastructure (rendering): типизированный константный объект.
// Единственный внешний импорт — тип шрифта TextStyle из React Native (R3, R6);
// фреймворковой логики нет — ни компонентов, ни Platform, ни анимаций.
//
// Связь с layout-движком (№32, ADR-0004): единица геометрии движка — символ,
// advance моноширинного шрифта цифр лада из этого файла. Движок шрифтов не
// видит (R1): рендерер умножает символы движка на измеренный advance
// fonts.fretDigits. Вертикальные метрики ROW_SPACING_CHARS = 2 и
// TEXT_ROW_SPACING_CHARS = 2 (src/domain/layout-engine/config.ts) объявлены
// финальными для этой темы (№32; TEXT_ROW_SPACING пересмотрен с 1: символ
// advance ~9.6px меньше кегля текстов колонок 12px — зазор/шаг стопки в 1
// символ давал наложение); тексты колонок — то же моно-семейство меньшим
// кеглем, шаг их стопки — 2 символа движка (№24); текст-строки —
// пропорциональное семейство, их перенос — забота рендерера (№6, ADR-0004).

import type { TextStyle } from 'react-native';

/**
 * Семейство цифр лада и текстов колонок (№32, №24): моноширинное — его
 * advance и есть символ, единица геометрии движка (ADR-0004). Платформенное
 * семейство Android; конкретный файл шрифта выбирается на этапе рендеров.
 */
const MONO_FAMILY = 'monospace';

/**
 * Семейство текст-строк ленты (№6, №32): пропорциональное. Платформенное
 * семейство Android (Roboto); конкретный файл шрифта — на этапе рендеров.
 */
const PROPORTIONAL_FAMILY = 'sans-serif';

/**
 * Зашитая тема рендера MVP (№32).
 */
export const theme = {
  /**
   * Шрифты (№32). Цифры лада — моноширинные (инвариант rendering-спеки);
   * тексты колонок — то же моно-семейство меньшим кеглем (№24: до 3 текстов
   * в стопке под колонкой, шаг стопки — 2 символа движка, №24/№32);
   * текст-строки — пропорциональное семейство покрупнее для читабельности.
   * lineHeight текст-строк (36) — бюджет строки ленты на строку переноса:
   * свободный остаток под кеглем 18 (~21px глиф) обязан покрывать выступ
   * цифр следующей системы вверх (~9.3px при advance ~9.6px); прежние 25px
   * давали остаток 3.9px — текст-строка наезжала на следующую таб-строку.
   * includeFontPadding выключен у текстов колонок — для будущих
   * Text-потребителей темы: высота строки Text не должна разъезжаться с
   * шагом стопки в 1 символ движка (№24). В Skia-рендере экрана этот флаг
   * не участвует: шаг стопки держит геометрия движка (координаты y в
   * символах) и базлайн-позиционирование (skia.ts).
   */
  fonts: {
    /** Цифры лада: база единицы геометрии движка (№32, ADR-0004). */
    fretDigits: {
      fontFamily: MONO_FAMILY,
      fontSize: 16,
    } satisfies TextStyle,

    /** Тексты колонок: моно-семейство, кегль 0.75 от цифр (№24). */
    columnText: {
      fontFamily: MONO_FAMILY,
      fontSize: 12,
      includeFontPadding: false,
    } satisfies TextStyle,

    /** Текст-строки ленты: пропорциональный шрифт (№6, №32). */
    textLine: {
      fontFamily: PROPORTIONAL_FAMILY,
      fontSize: 18,
      lineHeight: 36,
    } satisfies TextStyle,
  },

  /**
   * Вертикальный отступ текст-строк (px), применяется планом (plan.ts) СВЕРХУ
   * lineHeight-бюджета строк переноса: слот каждой строки переноса =
   * lineHeight, но первый глиф опускается на отступ от верха текст-строки,
   * а высота блока = строки·lineHeight + 2·отступ. Зачем: высота текст-строки
   * раньше совпадала с границами глифов, и первая/последняя строка прижимались
   * вплотную к линиям струн соседних таб-строк (скриншот №пользователь). Отступ
   * разделяет глифы и линейки, не трогая бюджет переноса.
   */
  textLinePaddingPx: 12,

  /**
   * Верхний отступ документа (px) до первой строки ленты — поля «тетради»
   * (№7: «как бумажная тетрадь»): лента строк (№6) начинается не от самого
   * края экрана, а ниже статус-бара, с зазором до первой строки. Зашито в
   * теме (№32), применяется при рендере как смещение y начала документа.
   */
  documentTopPaddingPx: 32,

  /**
   * Цвета (№32): «бумажная» палитра тетради — светлый фон, чернильные
   * линии и текст, акценты для черт, ручек и выделения (№36, №40).
   */
  colors: {
    /** Фон ленты — светлый, под бумагу (№7: «как бумажная тетрадь»). */
    background: '#FAF7F0',
    /** Струны, цифры и тексты — основной «чернильный» цвет. */
    ink: '#222222',
    /** Приглушённые элементы: сетка, серые ручки (№36). */
    muted: '#999999',
    /** Тактовые черты и корзина удаления — красный акцент (№18, №36). */
    barline: '#C0392B',
    /** Выделение ячейки/колонки/диапазона (№40). */
    selection: '#2E86C1',
  },

  /**
   * Прозрачность заливки выделения (№40; ревью ST-5, находка 13): визуальный
   * параметр рендера живёт в теме рядом с цветом выделения, не хардкодом в
   * Skia-переводчике (№32: единственный источник шрифтов, цветов и размеров).
   */
  selectionFillAlpha: 0.15,

  /**
   * Толщины линий в px (dp) рендера (№32): струны — волосные, черты
   * и ручки — заметно толще, выделение — поверх всего.
   */
  lineThickness: {
    /** Линии струн (№2: 4 строки, выводятся из tuning). */
    string: 1,
    /** Тактовая черта через все струны (№18). */
    barline: 2,
    /** Ручка-полоска текст-строки при захвате (№36). */
    textLineHandle: 2,
    /** Рамка выделения (№40). */
    selection: 2,
  },

  /**
   * Ширина левого отступа таб-строки под басовый ключ 𝄢 (№36) — в СИМВОЛАХ
   * движка, как всё, что умножается на advance (№32, ADR-0004): рендерер
   * отводит clefMarginChars × advance под ключ и ручку drag/удаления (№36).
   * Значение темы: ключ + запас под корзину удаления.
   */
  clefMarginChars: 4,
} as const;

/** Тип зашитой темы — для сигнатур рендереров (потребителей темы). */
export type Theme = typeof theme;
