// Детерминированная фабрика стабильных id сущностей (№19).
// Домен чистый (R1): без Math.random/uuid — генератор создаётся и передаётся
// явно (R6), что делает мутации воспроизводимыми и тривиально тестируемыми.
// Один генератор = один общий счётчик; уникальность в пределах тетради
// гарантируют префиксы по виду сущности. Приложение может подставить свою
// реализацию (uuid и т.п.) — интерфейс тот же.

import type { EntityId } from './types';

/** Префиксы id по видам сущностей: читаемость в JSON и логах (№19). */
export const ID_PREFIXES = {
  notebook: 'nb-',
  tabLine: 'tl-',
  textLine: 'tx-',
  column: 'c-',
  note: 'n-',
  columnText: 't-',
} as const;

/** Допустимый префикс id — один из зафиксированных видов сущностей. */
export type IdPrefix = (typeof ID_PREFIXES)[keyof typeof ID_PREFIXES];

/**
 * Генератор id: чистая функция; состояние (счётчик) живёт в замыкании
 * создавшего её генератора и передаётся в операции явно (R6).
 * Каждый вызов возвращает id, уникальный среди всех выданных этим
 * генератором (префикс различает виды сущностей).
 */
export type IdGenerator = (prefix: IdPrefix) => EntityId;

/**
 * Создаёт детерминированный генератор: первый вызов `gen('c-')` → `c-1`,
 * далее `c-2`, `n-3`, … — нумерация сквозная по порядку вызовов.
 */
export function createIdGenerator(): IdGenerator {
  let counter = 0;
  return (prefix) => `${prefix}${++counter}`;
}
