// Геометрические константы layout-движка (этап 3 дорожной карты, КАРТА §3).
// Спека: docs/specs/domains/layout-engine.md (разделы Configuration, Invariants).
// Слой Domain (R1): чистые константы — без I/O, шрифтов и фреймворков (№14).
//
// Ключевое решение (финализация №32): единица геометрии движка — СИМВОЛ,
// advance моноширинного шрифта цифр лада. Все координаты и ширины движок
// выдаёт в этих единицах; потребители (Skia-рендер экрана, HTML→PDF) умножают
// их на собственный advance, поэтому экранная и печатная геометрия всегда
// совпадают (№23), а сам движок остаётся свободным от шрифтов и фреймворков (R1).

/**
 * Минимальная ширина колонки в символах (№20): 2 символа на цифру лада
 * + по 1 символу отступа с каждой стороны. Каждая колонка стартует с этого
 * минимума и только растёт — под самый длинный свой текст (№20, №24).
 * От неё же арифметически считается ёмкость таб-строки (№20).
 */
export const MIN_COLUMN_WIDTH_CHARS = 4;

/**
 * Максимальная ширина колонки в символах (№20, №24): порог, по достижении
 * которого editing-домен отклоняет ввод текста колонки с предупреждением.
 * Сам движок текст колонки не обрезает и не переносит (№24).
 */
export const MAX_COLUMN_WIDTH_CHARS = 12;

/**
 * Доля целевой ширины, отведённая полосе систем (№20): ёмкость таб-строки
 * считается от «полосы» ~85% целевой ширины (экран/A4/превью, №23),
 * остаток — поля рендерера. Перенос (шаг WRAP, wrap.ts) сравнивает суммы
 * ширин колонок с шириной полосы в символах; число минимальных ячеек
 * (полоса ÷ MIN_COLUMN_WIDTH_CHARS) — производная метрика measure.ts.
 */
export const STRIP_WIDTH_FRACTION = 0.85;

/**
 * Интервал между соседними строками струн внутри системы, в символах.
 * ПРОБНОЕ ЗНАЧЕНИЕ (provisional): вертикальные метрики финализируются
 * на этапе 4 вместе со шрифтами рендера (№32); потребитель вправе умножить
 * на собственные интервалы. Список y строк струн выводится из tuning модели
 * (№2): stringY[i] = i * ROW_SPACING_CHARS, поэтому пятая струна (low B, №2)
 * не требует правок движка.
 */
export const ROW_SPACING_CHARS = 2;

/**
 * Зазор между нижней строкой струн системы и стопкой текстов колонок под ней,
 * в символах (№24: тексты рисуются под таб-строкой, до 3 на колонку, №6).
 * ПРОБНОЕ ЗНАЧЕНИЕ (provisional): финализируется на этапе 4 (№32) вместе
 * с метриками шрифтов текстов.
 */
export const TEXT_ROW_SPACING_CHARS = 1;
