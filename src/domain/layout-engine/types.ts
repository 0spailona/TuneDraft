// Выходной словарь layout-движка (этап 3 дорожной карты, КАРТА §3).
// Спека: docs/specs/domains/layout-engine.md (разделы Core Types, Flow).
// Слой Domain (R1): чистые типы, без I/O и фреймворков (№14); единственный
// внешний импорт — модель табулатуры (EntityId из ../tabulature/types).
// Единица всех координат и ширин — символ: advance моноширинного шрифта
// цифр лада (№32). Потребители (Skia-рендер экрана, HTML→PDF) умножают их
// на собственный advance, поэтому экранная и печатная геометрия всегда
// совпадают (№23), а движок остаётся свободным от шрифтов и фреймворков (R1).
// Модель хранит данные, а не координаты (№23): результат прохода — значение,
// повторный проход на тех же входах даёт идентичную геометрию (№14).

import type { EntityId } from '../tabulature/types';

/**
 * Разложенная колонка системы (№20): идентификатор колонки модели, x-офсет
 * левого края и ширина. Идёт в порядке колонок модели внутри своей системы.
 */
export interface LaidOutColumn {
  readonly columnId: EntityId;
  /** x-офсет левого края колонки от начала системы, в символах. */
  readonly xChars: number;
  /** Ширина колонки: от минимума 4 до потолка 12 символов (№20, №24). */
  readonly widthChars: number;
}

/**
 * Текст колонки в разложенной системе (№24): едет под таб-строкой вместе
 * со своей колонкой — x берётся у колонки, которая под него раздвинулась,
 * а не из собственной ширины текста (№24).
 */
export interface LaidOutColumnText {
  readonly textId: EntityId;
  /** Колонка-владелец текста (привязка по columnId, №19). */
  readonly columnId: EntityId;
  /** x-офсет левого края колонки-владельца, в символах (№24). */
  readonly xChars: number;
  /** y-офсет строки текста от верха системы, в символах (№24). */
  readonly yChars: number;
}

/**
 * Система (№20): фрагмент таб-строки, помещённый в полосу целевой ширины.
 * Разложение одной таб-строки — одна или несколько систем (перенос по тактам,
 * №18); каждая система раскладывается независимо от остальных (№28).
 */
export interface LaidOutSystem {
  /** Порядковый номер системы внутри таб-строки: 0, 1, 2… */
  readonly index: number;
  /** Колонки системы в порядке модели, с координатами (№20). */
  readonly columns: readonly LaidOutColumn[];
  /** Тексты колонок системы (№24): стопка под таб-строкой, x = x колонки. */
  readonly texts: readonly LaidOutColumnText[];
  /** Ширина полосы, отведённой системам, в символах (№20): floor(доля
   * STRIP_WIDTH_FRACTION от целевой ширины); остаток — поля рендерера (№23). */
  readonly widthChars: number;
}

/**
 * Разложенная таб-строка (№6): одна или несколько систем по ёмкости полосы
 * (№20) и вертикальные координаты строк струн, выведенные из tuning модели
 * (№2): stringY[i] = i * ROW_SPACING_CHARS — пятая струна (low B) не требует
 * правок движка (№2). Вертикальные метрики ПРОБНЫЕ (provisional):
 * финализируются на этапе 4 (№32).
 */
export interface TabLineLayout {
  readonly lineId: EntityId;
  /** Число строк струн — длина tuning модели таб-строки (№2). */
  readonly stringCount: number;
  /** y строк струн от верха таб-строки, в символах; y[i] = i * ROW_SPACING_CHARS. */
  readonly stringYChars: readonly number[];
  /** Системы строки по порядку переноса; минимум одна — даже для пустой строки. */
  readonly systems: readonly LaidOutSystem[];
}

/**
 * Разложенная текст-строка (№6): pass-through. Текст-строка не привязана
 * к нотам и колонкам (№6, №35), а её перенос — забота рендерера с пропорциональным
 * шрифтом тем (№32); движок лишь сохраняет позицию строки в ленте и сам текст.
 */
export interface TextLineLayout {
  readonly lineId: EntityId;
  /** Текст строки без изменений — движок не режет и не переносит его. */
  readonly text: string;
}

/**
 * Строка результата ленты (№6) — ровно один из двух видов, зеркало RibbonLine:
 * таб-раскладка или текст-строка pass-through. Различаются дискриминантом kind.
 */
export type RibbonLayoutEntry =
  (TabLineLayout & { readonly kind: 'tab' }) | (TextLineLayout & { readonly kind: 'text' });

/**
 * Результат одного прохода движка (№14, №23): полный layout тетради
 * на целевую ширину. Детерминированная функция (model, targetWidthChars):
 * повторный вызов на тех же входах даёт идентичную структуру (№14).
 */
export interface NotebookLayout {
  /** Лента результата: порядок строк ленты модели сохранён (№6). */
  readonly ribbon: readonly RibbonLayoutEntry[];
}
